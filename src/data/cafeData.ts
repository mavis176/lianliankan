/**
 * 动态无尽挑战关卡生成器
 */
export function generateEndlessLevel(tier: number): CafeLevelConfig {
  const rows = tier % 2 === 0 ? 10 : 8;
  const cols = tier % 3 === 0 ? 10 : 8;
  const iconCount = Math.min(12, 6 + Math.floor(tier / 3));
  const isMoves = tier % 2 === 1;
  const frozenCount = Math.min(24, Math.floor(tier * 1.5));
  const obstacles: ('none' | 'corners' | 'centerCross' | 'pillars' | 'maze')[] = [
    'none', 'corners', 'centerCross', 'pillars', 'maze'
  ];
  const obstacleType = obstacles[tier % obstacles.length];

  return {
    id: 100 + tier,
    title: `无尽挑战 · 第 ${tier} 层`,
    subtitle: `无尽模式 · 难度系数 Lv.${tier}`,
    rows,
    cols,
    iconCount,
    mode: isMoves ? 'moves' : 'time',
    timeLimit: isMoves ? 0 : Math.max(65, 110 - tier * 2),
    movesLimit: isMoves ? Math.max(30, 48 - Math.floor(tier / 2)) : undefined,
    frozenCount,
    obstacleType,
    targetScores: [tier * 800, tier * 1300, tier * 1900],
    rewardStars: 3,
    rewardCoins: 200 + tier * 50,
    description: `无尽进阶！当前第 ${tier} 层，网格 ${rows}×${cols}，包含 ${frozenCount} 块冰霜。`,
  };
}
